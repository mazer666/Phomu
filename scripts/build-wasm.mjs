#!/usr/bin/env node
/**
 * The WebAssembly module of the Rust base.
 * -------------------------------------------------------------------------
 * WHAT IT DOES
 *   1. It builds `platform/phomu-wasm` for `wasm32-unknown-unknown`.
 *   2. It runs `wasm-bindgen` over the artefact and writes the JavaScript
 *      glue to `src/core/generated/` and the module to `public/wasm/`.
 *   3. It writes a manifest with the version of the base to
 *      `public/wasm/phomu_core.manifest.json`.
 *
 * WHY
 *   The web shell is a static export and has no server that could host the
 *   base. WebAssembly is the only way for the shell to use the rules of the
 *   base without owning a second implementation
 *   (docs/design/BUILD-CONTRACT.md § 2.4, rule B-7).
 *
 *   The module is a static asset: `output: 'export'` survives.
 *
 * USAGE
 *   node scripts/build-wasm.mjs
 *
 * REQUIREMENTS
 *   - the Rust toolchain with the target `wasm32-unknown-unknown`
 *     (`rustup target add wasm32-unknown-unknown`)
 *   - `wasm-bindgen` in the same version as the crate uses. The script finds
 *     it in `PATH`, in `tools/.cache/` or downloads the pinned release.
 */

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const TARGET = 'wasm32-unknown-unknown';
const GENERATED_DIR = path.join(REPO_ROOT, 'src', 'core', 'generated');
const PUBLIC_DIR = path.join(REPO_ROOT, 'public', 'wasm');
const CACHE_DIR = path.join(REPO_ROOT, 'tools', '.cache');

/**
 * The header that marks the generated files.
 *
 * WHY: the file-size gate and the linters have to know that the files are
 * generated and must not be maintained by hand.
 */
const HEADER = `/* Generated by scripts/build-wasm.mjs — do not edit. */\n`;

/**
 * Runs a command and stops the build when it fails.
 *
 * @param {string} command - The command to run.
 * @param {string[]} args - The arguments of the command.
 * @param {object} [options] - The options of the command.
 * @returns {string} The output of the command.
 */
function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    ...options,
  });
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? '');
    process.stderr.write(result.stderr ?? '');
    throw new Error(`${command} ${args.join(' ')} failed`);
  }
  return result.stdout ?? '';
}

/**
 * The version of `wasm-bindgen` the crate uses.
 *
 * WHY the lock file: the CLI has to match the version of the crate, or the
 * generated glue does not fit the module.
 *
 * @returns {string} The version, e.g. `0.2.129`.
 */
function wasmBindgenVersion() {
  const lock = fs.readFileSync(path.join(REPO_ROOT, 'Cargo.lock'), 'utf8');
  const match = lock.match(/name = "wasm-bindgen"\nversion = "([^"]+)"/);
  if (!match) {
    throw new Error('the version of wasm-bindgen is not in Cargo.lock');
  }
  return match[1];
}

/**
 * The platform triple of the host.
 *
 * WHY `musl` on Linux: the release of the CLI ships a static build for
 * `x86_64-unknown-linux-musl`. It runs on every Linux distribution.
 *
 * @returns {string} The triple, e.g. `x86_64-unknown-linux-musl`.
 */
function hostTriple() {
  const arch = process.arch === 'arm64' ? 'aarch64' : 'x86_64';
  if (process.platform === 'darwin') {
    return `${arch}-apple-darwin`;
  }
  return `${arch}-unknown-linux-musl`;
}

/**
 * Finds the `wasm-bindgen` CLI — in the path, in the cache or as a download.
 *
 * WHY a download: the CI does not install the CLI, and the version has to
 * match the crate. The release of the version is a static binary.
 *
 * @param {string} version - The version of the CLI.
 * @returns {string} The path of the binary.
 */
function findWasmBindgen(version) {
  const inPath = spawnSync('wasm-bindgen', ['--version'], { encoding: 'utf8' });
  if (inPath.status === 0 && inPath.stdout.includes(version)) {
    return 'wasm-bindgen';
  }
  const cached = path.join(
    CACHE_DIR,
    `wasm-bindgen-${version}-${hostTriple()}`,
    'wasm-bindgen'
  );
  if (fs.existsSync(cached)) {
    return cached;
  }
  const archive = path.join(CACHE_DIR, `wasm-bindgen-${version}.tar.gz`);
  const base = `https://github.com/rustwasm/wasm-bindgen/releases/download/${version}/wasm-bindgen-${version}-${hostTriple()}.tar.gz`;
  console.log(`downloading ${base}`);
  fs.mkdirSync(CACHE_DIR, { recursive: true });
  const download = spawnSync('curl', ['-sSL', '-o', archive, base], {
    encoding: 'utf8',
  });
  if (download.status !== 0) {
    throw new Error(`wasm-bindgen ${version} could not be downloaded`);
  }
  // The release publishes the checksum of every archive. The build verifies
  // it, so that a damaged download cannot become a build artefact.
  const checksum = spawnSync('curl', ['-sSL', `${base}.sha256sum`], {
    encoding: 'utf8',
  });
  if (checksum.status === 0) {
    const expected = checksum.stdout.trim().split(/\s+/)[0];
    const actual = createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
    if (expected !== actual) {
      throw new Error(
        `the checksum of wasm-bindgen ${version} does not match (${actual} != ${expected})`
      );
    }
  }
  const target = path.dirname(cached);
  fs.mkdirSync(target, { recursive: true });
  run('tar', ['xzf', archive, '-C', target, '--strip-components=1']);
  fs.chmodSync(cached, 0o755);
  return cached;
}

/**
 * The version of the surface of the base.
 *
 * WHY the source and not the module: the manifest has to name the version
 * of the base the module was built from
 * (docs/design/BUILD-CONTRACT.md § 2.1).
 *
 * @returns {string} The version, e.g. `1.0.0`.
 */
function readAbiVersion() {
  const source = fs.readFileSync(
    path.join(REPO_ROOT, 'core', 'phomu-core', 'src', 'abi.rs'),
    'utf8'
  );
  const major = source.match(/ABI_VERSION_MAJOR: u\d+ = (\d+)/);
  const minor = source.match(/ABI_VERSION_MINOR: u\d+ = (\d+)/);
  const patch = source.match(/ABI_VERSION_PATCH: u\d+ = (\d+)/);
  if (!major || !minor || !patch) {
    throw new Error('the version of the surface is not in core/phomu-core/src/abi.rs');
  }
  return `${major[1]}.${minor[1]}.${patch[1]}`;
}

function main() {
  const version = wasmBindgenVersion();
  const cli = findWasmBindgen(version);

  console.log('Building the WebAssembly module of the base');
  console.log('='.repeat(72));
  run('cargo', [
    'build',
    '--release',
    '--target',
    TARGET,
    '-p',
    'phomu-wasm',
  ]);

  const artefact = path.join(
    REPO_ROOT,
    'target',
    TARGET,
    'release',
    'phomu_wasm.wasm'
  );
  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  fs.mkdirSync(PUBLIC_DIR, { recursive: true });
  run(cli, [
    '--target',
    'web',
    '--out-dir',
    GENERATED_DIR,
    '--out-name',
    'phomu_wasm',
    artefact,
  ]);

  // The header marks the files as generated: the file-size gate and the
  // linters have to know that they must not be maintained by hand.
  for (const name of ['phomu_wasm.js', 'phomu_wasm.d.ts']) {
    const file = path.join(GENERATED_DIR, name);
    const content = fs.readFileSync(file, 'utf8');
    if (!content.startsWith(HEADER)) {
      fs.writeFileSync(file, `${HEADER}${content}`);
    }
  }

  // The glue loads the module with `new URL('phomu_wasm_bg.wasm',
  // import.meta.url)`, so the binary has to stay **next to the glue**: the
  // bundler resolves the URL relative to the module and emits the file as an
  // asset. The copy in `public/` is the runtime fallback for a shell that
  // fetches the module by URL instead of importing it.
  fs.copyFileSync(
    path.join(GENERATED_DIR, 'phomu_wasm_bg.wasm'),
    path.join(PUBLIC_DIR, 'phomu_core_bg.wasm')
  );
  fs.rmSync(path.join(GENERATED_DIR, 'phomu_wasm_bg.wasm.d.ts'));

  const abi = readAbiVersion();
  fs.writeFileSync(
    path.join(PUBLIC_DIR, 'phomu_core.manifest.json'),
    `${JSON.stringify({ schemaVersion: 1, wasmBindgen: version, abi }, null, 2)}\n`
  );

  const size = fs.statSync(path.join(PUBLIC_DIR, 'phomu_core_bg.wasm')).size;
  console.log(`module:   public/wasm/phomu_core_bg.wasm (${size} bytes)`);
  console.log(`glue:     src/core/generated/phomu_wasm.js`);
  console.log(`bindgen:  ${version}`);
}

main();
