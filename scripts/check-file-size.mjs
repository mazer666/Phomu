#!/usr/bin/env node
/**
 * Quality gate: file size (CONTRACT §6, ARCHITECTURE.md §6.1)
 * -------------------------------------------------------------------------
 * WHAT IT CHECKS
 *   The physical line count (identical to `wc -l`) of every hand-written
 *   source file of the repository — the TypeScript shell **and** the Rust
 *   base — against two limits:
 *
 *     soft limit  400 lines   a new file above it is an error
 *     hard limit  550 lines   the maximum of a hand-written source file
 *
 *   The gate has three channels (QA-ARC-001, QA-09 backlog item 2.1):
 *
 *   1. NEW FILE OVER THE SOFT LIMIT  ->  error, exit code 1.
 *      A new file never receives an exception. That is the point of the
 *      rule: the exception list is a record of the past, not a licence for
 *      the future.
 *
 *   2. KNOWN LEGACY FILE THAT GREW     ->  error, exit code 1.
 *      The recorded state of a known legacy file is a high-water mark. A
 *      file that grows beyond it is the exact regression the gate was
 *      built for, and it is an error.
 *
 *   3. KNOWN LEGACY FILE THAT SHRANK   ->  success, and the recorded
 *      state is updated **downward automatically** (the same run writes
 *      the exceptions file back). The progress of the refactoring is
 *      therefore recorded instead of being lost, and the exception list
 *      converges to zero as the backlog is worked.
 *
 *   A known legacy file at or below its recorded state stays a warning
 *   with the reference to the open refactoring (GAP-007) — the limit is
 *   still breached, but the breach is not growing.
 *
 * SCOPE
 *   `src/**\/*.{ts,tsx}`  (the TypeScript shell)
 *   `core/**\/*.rs`, `platform/**\/*.rs`, `tools/**\/*.rs`  (the Rust base)
 *
 *   The scope is data, not code: `scripts/file-size.exceptions.json` holds
 *   the recorded state of every known legacy file, with the reason of the
 *   exception. The gate rewrites that file when a file shrinks.
 *
 * GENERATED FILES
 *   Files whose header carries a generated marker (`auto-generated`,
 *   `generated by`, `do not edit`, `@generated`, `code generated`) are
 *   skipped: they are not maintained by hand and therefore not reviewable.
 *   Affected: `src/data/songs/index.ts` (produced by
 *   `scripts/migrate_and_deduplicate.py`) and `src/i18n/variant-keys.ts`
 *   (produced by `scripts/generate-variant-keys.mjs`).
 *
 * OPTIONS
 *   --root=<path>        check a different tree (the isolated proof)
 *   --exceptions=<path>  check against a different exception table
 *   --no-update          never write the exception table back
 *   --quiet              print only the findings and the summary
 *
 * EXAMPLE
 *   node scripts/check-file-size.mjs
 *   node scripts/check-file-size.mjs --root=scripts/fixtures/file-size/ok
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const DEFAULT_EXCEPTIONS = path.join(SCRIPT_DIR, 'file-size.exceptions.json');

/** Default limits. The exception table may override them. */
const DEFAULT_SOFT_LIMIT = 400;
const DEFAULT_HARD_LIMIT = 550;

/**
 * The scope of the gate: a directory and the file extensions it contains.
 * Every entry is counted separately, so the report names the languages.
 */
const SCOPES = [
  { id: 'typescript', label: 'TypeScript', dirs: ['src'], extensions: ['.ts', '.tsx'] },
  { id: 'rust', label: 'Rust', dirs: ['core', 'platform', 'tools'], extensions: ['.rs'] },
];

/** Markers that identify a generated file. */
const GENERATED_MARKERS = [
  /auto-?generated/i,
  /generated by/i,
  /do not edit/i,
  /@generated/i,
  /code generated/i,
];

/** Directories that are not traversed. */
const IGNORED_DIRS = new Set([
  'node_modules',
  '.next',
  'coverage',
  'out',
  'target',
  '.git',
  'build',
  '.gradle',
]);

/**
 * Read an option of the form `--name=value`.
 *
 * @param {string} name the option name
 * @param {string|undefined} fallback the value used when the option is absent
 * @returns {string} the value of the option
 */
function option(name, fallback) {
  const prefix = `--${name}=`;
  const found = process.argv.slice(2).find((argument) => argument.startsWith(prefix));
  return found ? found.slice(prefix.length) : fallback;
}

/**
 * Collect the source files of one directory.
 *
 * @param {string} dir the absolute directory
 * @param {string[]} extensions the extensions that count as source
 * @param {string[]} [out] the collected files
 * @returns {string[]} the collected files
 */
function collectSourceFiles(dir, extensions, out = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRS.has(entry.name)) continue;
      collectSourceFiles(full, extensions, out);
    } else if (entry.isFile() && extensions.includes(path.extname(entry.name))) {
      out.push(full);
    }
  }
  return out;
}

/**
 * Counts the physical lines (identical to `wc -l`).
 *
 * @param {string} content the file content
 * @returns {number} the number of lines
 */
export function countLines(content) {
  if (content === '') return 0;
  const parts = content.split(/\r?\n/);
  return parts[parts.length - 1] === '' ? parts.length - 1 : parts.length;
}

/**
 * Extract the leading comment block of a file.
 *
 * WHY: the generated marker has to be read in the *header* of a file. A
 * hand-written Rust file may well mention a generated file in its prose
 * (`build.rs` writes a generated module, `generate-header.rs` writes a
 * generated header) — such a mention must not exempt the file from the
 * gate.
 *
 * @param {string} content the file content
 * @returns {string} the leading comment block
 */
export function leadingCommentBlock(content) {
  const lines = content.split(/\r?\n/);
  /** @type {string[]} */
  const block = [];
  let insideBlockComment = false;
  for (const line of lines) {
    const trimmed = line.trim();
    if (insideBlockComment) {
      block.push(line);
      if (trimmed.includes('*/')) insideBlockComment = false;
      continue;
    }
    if (trimmed.startsWith('/*')) {
      block.push(line);
      insideBlockComment = !trimmed.includes('*/');
      continue;
    }
    if (trimmed.startsWith('//')) {
      block.push(line);
      continue;
    }
    break;
  }
  return block.join('\n');
}

/**
 * Checks whether a file is generated (header comment).
 *
 * @param {string} content the file content
 * @returns {boolean} true when the header carries a generated marker
 */
export function isGenerated(content) {
  const head = leadingCommentBlock(content);
  return GENERATED_MARKERS.some((marker) => marker.test(head));
}

/**
 * Read the exception table.
 *
 * @param {string} exceptionsPath the path of the table
 * @returns {{limits: {soft: number, hard: number}, exceptions: Record<string, {lines: number, reason: string}>}}
 *   the limits and the recorded states
 */
export function readExceptions(exceptionsPath) {
  let raw;
  try {
    raw = fs.readFileSync(exceptionsPath, 'utf8');
  } catch {
    return { limits: { soft: DEFAULT_SOFT_LIMIT, hard: DEFAULT_HARD_LIMIT }, exceptions: {} };
  }
  const parsed = JSON.parse(raw);
  return {
    limits: {
      soft: parsed.softLimit ?? DEFAULT_SOFT_LIMIT,
      hard: parsed.hardLimit ?? DEFAULT_HARD_LIMIT,
    },
    exceptions: parsed.exceptions ?? {},
  };
}

/**
 * Run the gate.
 *
 * @param {{
 *   root?: string,
 *   exceptionsPath?: string,
 *   update?: boolean,
 * }} [options] the options of the run
 * @returns {{
 *   files: {typescript: number, rust: number},
 *   generated: {file: string, lines: number}[],
 *   warnings: {file: string, lines: number, text: string}[],
 *   errors: {file: string, lines: number, text: string}[],
 *   notes: string[],
 *   ioErrors: string[],
 *   changed: boolean,
 * }} the result of the gate
 */
export function runFileSizeCheck(options = {}) {
  const root = path.resolve(options.root ?? REPO_ROOT);
  const update = options.update !== false;

  // The exception table belongs to the repository: it records the state of
  // the files of the repository. A tree that is checked in isolation has
  // its own files and therefore its own table.
  const isRepository = root === REPO_ROOT;
  const hasTable = options.exceptionsPath !== undefined || isRepository;
  const exceptionsPath = path.resolve(options.exceptionsPath ?? DEFAULT_EXCEPTIONS);

  const { limits, exceptions } = hasTable
    ? readExceptions(exceptionsPath)
    : { limits: { soft: DEFAULT_SOFT_LIMIT, hard: DEFAULT_HARD_LIMIT }, exceptions: {} };
  const { soft: SOFT_LIMIT, hard: HARD_LIMIT } = limits;

  const generated = [];
  const warnings = [];
  const errors = [];
  const notes = [];
  const ioErrors = [];
  const files = { typescript: 0, rust: 0 };

  /** The files that were seen, relative to the root. */
  const seen = new Set();
  /** The exception entries that have to change. */
  let changed = false;

  for (const scope of SCOPES) {
    for (const dir of scope.dirs) {
      const absolute = path.join(root, dir);
      for (const file of collectSourceFiles(absolute, scope.extensions)) {
        const relative = path.relative(root, file).split(path.sep).join('/');
        seen.add(relative);

        let content;
        try {
          content = fs.readFileSync(file, 'utf8');
        } catch (error) {
          ioErrors.push(
            `${relative}: file not readable (${error.code ?? error.message})`
          );
          continue;
        }

        const lines = countLines(content);
        files[scope.id] += 1;

        if (isGenerated(content)) {
          generated.push({ file: relative, lines });
          continue;
        }

        const record = exceptions[relative];

        if (!record) {
          // Channel 1: a new file never receives an exception.
          if (lines > SOFT_LIMIT) {
            const text =
              lines > HARD_LIMIT
                ? `new file above the hard limit (${HARD_LIMIT}) by ${lines - HARD_LIMIT} lines`
                : `new file above the soft limit (${SOFT_LIMIT}) by ${lines - SOFT_LIMIT} lines`;
            errors.push({ file: relative, lines, text });
          }
          continue;
        }

        if (lines > record.lines) {
          // Channel 2: the legacy file grew beyond its recorded state.
          errors.push({
            file: relative,
            lines,
            text:
              `grew by ${lines - record.lines} lines beyond its recorded state ` +
              `(${record.lines}) — the legacy file must not grow; refactoring still open: ` +
              `${record.reason}`,
          });
          continue;
        }

        // Channel 3: the legacy file is at or below its recorded state.
        if (lines > SOFT_LIMIT) {
          const breach =
            lines > HARD_LIMIT
              ? `above the hard limit (${HARD_LIMIT}) by ${lines - HARD_LIMIT} lines`
              : `above the soft limit (${SOFT_LIMIT}) by ${lines - SOFT_LIMIT} lines`;
          warnings.push({
            file: relative,
            lines,
            text:
              `known legacy file ${breach} — refactoring still open: ${record.reason}`,
          });
        }

        if (lines < record.lines) {
          record.lines = lines;
          changed = true;
          notes.push(
            `${relative}: the recorded state was updated downward to ${lines} lines.`
          );
        }
        if (lines <= SOFT_LIMIT) {
          delete exceptions[relative];
          changed = true;
          notes.push(
            `${relative}: the recorded exception is no longer needed — the file is ` +
              `below the soft limit (${SOFT_LIMIT}) and was removed from the table.`
          );
        }
      }
    }
  }

  // The exception entries whose file does not exist any more.
  for (const file of Object.keys(exceptions)) {
    if (seen.has(file)) continue;
    delete exceptions[file];
    changed = true;
    notes.push(
      `${file}: the recorded exception was stale (the file no longer exists) and was removed.`
    );
  }

  if (changed && update && hasTable) {
    writeExceptions(exceptionsPath, exceptions, limits);
  }

  return {
    files,
    limits: { soft: SOFT_LIMIT, hard: HARD_LIMIT },
    legacy: Object.keys(exceptions).length,
    generated,
    warnings,
    errors,
    notes,
    ioErrors,
    changed,
  };
}

/**
 * Write the exception table back.
 *
 * @param {string} exceptionsPath the path of the table
 * @param {Record<string, {lines: number, reason: string}>} exceptions the recorded states
 * @param {{soft: number, hard: number}} limits the limits of the gate
 * @returns {boolean} true when the table was written
 */
function writeExceptions(exceptionsPath, exceptions, limits) {
  const document = {
    $comment: [
      'The recorded state of every known legacy file above the soft limit.',
      'Source of truth: ARCHITECTURE.md §6.1, REQUIREMENTS.md NFR-009 / GAP-007.',
      'The gate scripts/check-file-size.mjs reads this table and rewrites it',
      'when a legacy file shrinks. A new file above the soft limit is an error',
      'and is therefore never recorded here.',
      'Change a recorded state upward only together with an ADR.',
    ],
    schemaVersion: 1,
    softLimit: limits.soft,
    hardLimit: limits.hard,
    exceptions: sortExceptions(exceptions),
  };
  try {
    fs.writeFileSync(exceptionsPath, `${JSON.stringify(document, null, 2)}\n`, 'utf8');
    return true;
  } catch {
    return false;
  }
}

/**
 * Sort the exception entries by path, so that the table stays stable.
 *
 * @param {Record<string, {lines: number, reason: string}>} exceptions the recorded states
 * @returns {Record<string, {lines: number, reason: string}>} the sorted states
 */
function sortExceptions(exceptions) {
  /** @type {Record<string, {lines: number, reason: string}>} */
  const sorted = {};
  for (const key of Object.keys(exceptions).sort()) {
    sorted[key] = exceptions[key];
  }
  return sorted;
}

// Only run when the file was started directly as a CLI.
const invokedDirectly =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  const root = path.resolve(option('root', REPO_ROOT));
  const exceptionsOption = option('exceptions', undefined);
  const exceptionsPath = exceptionsOption ? path.resolve(exceptionsOption) : undefined;
  const quiet = process.argv.includes('--quiet');
  const update = !process.argv.includes('--no-update');

  /**
   * Print a line unless the gate runs in the quiet mode.
   *
   * @param {string} text the line to print
   */
  const say = (text) => {
    if (!quiet) console.log(text);
  };

  const result = runFileSizeCheck({ root, exceptionsPath, update });

  say('Phomu quality gate: file size');
  say(
    `Source files checked: ${result.files.typescript} TypeScript, ${result.files.rust} Rust`
  );
  say(
    `Limits: target ${result.limits.soft} lines (warning), maximum ${result.limits.hard} lines (error)`
  );

  if (result.generated.length > 0) {
    say(`\nSkipped (generated): ${result.generated.length}`);
    for (const gen of result.generated) {
      say(`   ${gen.file} (${gen.lines} lines, generated)`);
    }
  }

  if (result.notes.length > 0) {
    say(`\nRecorded state updates: ${result.notes.length}`);
    for (const note of result.notes) {
      say(`   ${note}`);
    }
  }

  if (result.warnings.length > 0) {
    say(`\n⚠️  ${result.warnings.length} warning(s):`);
    for (const warning of result.warnings) {
      say(`   ${warning.file}: ${warning.lines} lines — ${warning.text}`);
    }
  }

  if (result.ioErrors.length > 0) {
    say(`\n⚠️  ${result.ioErrors.length} read error(s):`);
    for (const ioError of result.ioErrors) {
      say(`   ${ioError}`);
    }
  }

  if (result.errors.length > 0) {
    console.error(
      `\n❌ ${result.errors.length} error(s):`
    );
    for (const error of result.errors) {
      console.error(`   ${error.file}: ${error.lines} lines — ${error.text}`);
    }
    process.exit(1);
  }

  const legacy = result.legacy;
  say(
    `\n✅ Gate passed — 0 errors, ${result.warnings.length} warning(s), ` +
      `${legacy} known legacy file(s).`
  );
  process.exit(0);
}
