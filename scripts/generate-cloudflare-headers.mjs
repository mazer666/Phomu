#!/usr/bin/env node
/**
 * Writes the security headers into `public/_headers` for Cloudflare Pages.
 *
 * WHY: a static export has no server that could set the headers, and
 * Cloudflare Pages reads them from a plain text file in the static
 * directory. The list comes from `config/security-headers.mjs`, the same
 * source the Next.js server uses, so the two hosts cannot drift apart.
 *
 * The file is **generated**: it is written by this script and checked by
 * `scripts/check-cloudflare-headers.mjs`. It is committed so that a build
 * without the script still ships the headers, and the check makes an
 * outdated file visible.
 *
 * Usage:
 *   node scripts/generate-cloudflare-headers.mjs          # write the file
 *   node scripts/generate-cloudflare-headers.mjs --check  # compare only
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { securityHeaders } from '../config/security-headers.mjs';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const TARGET = path.join(REPO_ROOT, 'public', '_headers');
const CHECK_ONLY = process.argv.includes('--check');

/**
 * The rules of the `_headers` file.
 *
 * WHY one rule for everything: the shell has no route that may be served
 * without the headers, and a rule per route would be a place to forget
 * one. The API paths are excluded because Cloudflare does not apply
 * `_headers` to the responses of a Pages Function — a function has to
 * attach the headers itself.
 *
 * @returns {string} the content of the file
 */
function render() {
  const lines = [
    '# Generated by scripts/generate-cloudflare-headers.mjs — do not edit.',
    '# The source of truth is config/security-headers.mjs.',
    '#',
    '# One rule for the whole site: no path may be served without the',
    '# headers. The API paths are listed separately because Cloudflare does',
    '# not apply `_headers` to a Pages Function response — the function',
    '# attaches the headers itself.',
    '',
    '/*',
  ];
  for (const header of securityHeaders) {
    lines.push(`  ${header.key}: ${header.value}`);
  }
  lines.push('');
  return lines.join('\n');
}

const expected = render();

if (CHECK_ONLY) {
  const actual = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (actual !== expected) {
    console.error('❌ public/_headers does not match config/security-headers.mjs.');
    console.error('   Run: node scripts/generate-cloudflare-headers.mjs');
    process.exit(1);
  }
  console.log('✅ public/_headers matches config/security-headers.mjs');
  process.exit(0);
}

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, expected, 'utf8');
console.log(
  `✅ public/_headers written — ${securityHeaders.length} headers for the pattern /*`
);
